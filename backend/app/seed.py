"""Demo data: 1 seller, 2 bidders and lots in every state.

Run automatically on first start (SEED_ON_START=true, only when the DB is empty) or manually:
    python -m app.seed            # seed if empty
    python -m app.seed --reset    # DROP everything and seed again (also refreshes the demo times)
"""
import sys
from datetime import timedelta

from sqlalchemy import select

from .db import Base, SessionLocal, engine
from .errors import ApiError
from .models import User, WalletTransaction, utcnow
from .security import hash_password
from .services import external
from .services.auction import create_lot, place_bid, settle_lot
from .services.external import ItemDTO

DEMO_PASSWORD = "demo1234"

# Used when the external API is unreachable at seed time (images fall back to the UI placeholder).
FALLBACK_ITEMS = [
    ("Noite Estrelada sobre o Rio", "Vincent van Gogh", "1888"), ("Nenúfares", "Claude Monet", "1906"),
    ("Dançarinas Azuis", "Edgar Degas", "1899"), ("O Quarto em Arles", "Vincent van Gogh", "1889"),
    ("Paisagem de Outono", "Camille Pissarro", "1872"), ("Retrato de Jovem", "Pierre-Auguste Renoir", "1876"),
]


SEED_QUERIES = ["impressionism", "landscape painting", "portrait", "still life", "flowers"]


def _items(db) -> list[ItemDTO]:
    """Real artworks (with pictures) from the Cleveland Museum of Art API; falls back to image-less demo items if it is unreachable."""
    found: dict[str, ItemDTO] = {}
    for q in SEED_QUERIES:
        try:
            for raw in external.search_items(db, q, 1, 20)["items"]:
                found.setdefault(raw["external_id"], ItemDTO(**raw))
        except ApiError:
            break  # API down: no point in trying the other queries
        if len(found) >= 8:
            break
    if len(found) >= 6:
        print(f"[seed] {len(found)} itens reais (com imagem) obtidos da API do Cleveland Museum of Art.")
        return list(found.values())
    reason = external._Breaker.last_error or "a API devolveu poucos itens com imagem"
    print(f"[seed] ATENÇÃO: usando itens de demonstração SEM imagem. Motivo: {reason}")
    print("[seed] Com a internet funcionando, rode `python -m app.seed --reset` para tentar de novo.")
    return [ItemDTO(external_id=f"demo-{n}", title=t, image_url=None, thumb_url=None, source="demo",
                    description="Item de demonstração (API externa indisponível durante o seed).",
                    attributes={"Artista": a, "Data": d}) for n, (t, a, d) in enumerate(FALLBACK_ITEMS)]


def seed_if_empty() -> None:
    with SessionLocal() as db:
        if db.execute(select(User.id).limit(1)).first():
            return
        try:
            seed(db)
        except Exception:
            db.rollback()
            Base.metadata.drop_all(engine)   # never leave half-seeded data behind (it would block the next seed)
            Base.metadata.create_all(engine)
            raise


def seed(db) -> None:
    now = utcnow()
    pw = hash_password(DEMO_PASSWORD)
    seller = User(name="Galeria Demo", email="leiloeiro@demo.com", password_hash=pw, role="seller")
    ana = User(name="Ana Souza", email="ana@demo.com", password_hash=pw, role="bidder", balance_cents=50_000_00)
    bruno = User(name="Bruno Lima", email="bruno@demo.com", password_hash=pw, role="bidder", balance_cents=30_000_00)
    db.add_all([seller, ana, bruno])
    db.flush()
    db.add_all([WalletTransaction(user_id=u.id, kind="deposit", amount_cents=u.balance_cents,
                                  created_at=now - timedelta(days=5)) for u in (ana, bruno)])
    db.commit()

    items = _items(db)
    reais = 100

    def lot(i, start, inc, starts, ends, created=None):
        # backdated demo lots need a backdated 'now', otherwise create_lot would move the start to the present
        return create_lot(db, seller, items[i], start * reais, inc * reais, starts, ends, now=created or min(starts, now))

    # 1) live for two weeks, with a bidding war (Ana is currently leading, Bruno was outbid)
    l1 = lot(0, 1000, 100, now - timedelta(hours=2), now + timedelta(days=14))
    for who, amount, ago in ((ana, 1000, 90), (bruno, 1200, 60), (ana, 1500, 30)):
        place_bid(db, l1.id, who.id, amount * reais, now=now - timedelta(minutes=ago))
    # 2) live, ends in 20 minutes: good for seeing the countdown and anti-sniping
    l2 = lot(1, 500, 50, now - timedelta(hours=1), now + timedelta(minutes=20))
    place_bid(db, l2.id, bruno.id, 550 * reais, now=now - timedelta(minutes=10))
    # 3) live without bids
    lot(2, 800, 100, now - timedelta(minutes=5), now + timedelta(days=7))
    # 4) scheduled
    lot(3, 1200, 200, now + timedelta(days=1), now + timedelta(days=4))
    # 5) ended with winner (receipt generated by the regular settlement code)
    past = now - timedelta(days=3)
    l5 = lot(4, 300, 50, past, now - timedelta(days=1), created=past)
    place_bid(db, l5.id, ana.id, 300 * reais, now=past + timedelta(hours=5))
    place_bid(db, l5.id, bruno.id, 400 * reais, now=past + timedelta(hours=9))
    settle_lot(db, l5.id, now=l5.ends_at + timedelta(seconds=1))
    # 6) ended without bids
    l6 = lot(5, 250, 25, past, now - timedelta(days=2), created=past)
    settle_lot(db, l6.id, now=l6.ends_at + timedelta(seconds=1))


if __name__ == "__main__":
    if "--reset" in sys.argv:
        Base.metadata.drop_all(engine)
    Base.metadata.create_all(engine)
    seed_if_empty()
    print("Seed done. Accounts (password demo1234): leiloeiro@demo.com, ana@demo.com, bruno@demo.com")